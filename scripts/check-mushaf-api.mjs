import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/utils/mushafApi.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { fetchMushafPage, printedMushafImageUrl, findMushafPage, validMushafPage } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const signal = new AbortController().signal;
assert.equal(validMushafPage(1), true);
assert.equal(validMushafPage(604), true);
for (const value of [0, 605, 1.5, NaN]) assert.equal(validMushafPage(value), false);
let requests = 0;
const ayah = { number: 1, text: 'Arabic API text', numberInSurah: 1, page: 1, juz: 1, hizbQuarter: 1, surah: { number: 1, name: 'Al-Fatihah', englishName: 'The Opening' } };
globalThis.fetch = async () => { requests++; return { ok: true, json: async () => ({ code: 200, data: { ayahs: [ayah] } }) }; };
assert.deepEqual(await fetchMushafPage(1, signal), [ayah]);
await fetchMushafPage(1, signal);
assert.equal(requests, 1, 'Repeated pages should use the cache');
await assert.rejects(fetchMushafPage(0, signal), /1 to 604/);
await assert.rejects(fetchMushafPage(2, signal), /unavailable/, 'Mismatched page data must be rejected');
globalThis.fetch = async () => ({ ok: false });
await assert.rejects(fetchMushafPage(3, signal), /could not be loaded/);
globalThis.fetch = async url => ({ ok: true, json: async () => ({ code: 200, data: url.includes('/ayah/') ? ayah : { ayahs: [ayah] } }) });
assert.equal(await findMushafPage('surah', 1, signal), 1);
assert.equal(await findMushafPage('juz', 1, signal), 1);
await assert.rejects(findMushafPage('juz', 31, signal), /valid index/);
console.log('Mushaf API checks passed: page limits, caching, response validation, failures, and index lookup.');

assert.ok(printedMushafImageUrl(1).endsWith('/page001.png'));
assert.ok(printedMushafImageUrl(604).endsWith('/page604.png'));
assert.throws(() => printedMushafImageUrl(605), /1 to 604/);
console.log('Printed page checks passed: page numbering and boundaries.');
